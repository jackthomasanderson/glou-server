import nextCoreWebVitals from 'eslint-config-next/core-web-vitals';
import nextTypescript from 'eslint-config-next/typescript';

// `next lint` was removed in Next.js 16 (see CI run #174 — it now misparses
// "lint" as a positional project-directory arg), so ESLint is invoked
// directly via the "lint": "eslint ." script instead. eslint-config-next 16
// already ships native ESLint 9 flat-config arrays (no FlatCompat bridging
// needed — wrapping these already-flat configs in FlatCompat double-wraps
// the plugin objects and crashes with a circular-structure error).
const FETCH_MESSAGE = 'Call the API through request, requestJson or client from @/lib/api: deadline, cookie and error codes (#619).';

const eslintConfig = [
  ...nextCoreWebVitals,
  ...nextTypescript,
  {
    ignores: ['node_modules/**', '.next/**', 'public/**'],
  },
  // #654: dialogs go through ResponsiveModal, which turns them into a
  // full-screen sheet on phones (ux-ui.md §5.4). Six plain `Modal`s had
  // slipped past the #328 migration with nothing to catch them.
  {
    files: ['**/*.{ts,tsx}'],
    ignores: [
      'components/ui/ResponsiveModal.tsx', // the wrapper itself
      'components/ui/BottomNav.tsx', // the "More" menu is a bottom sheet on purpose, never full-screen
      '**/__tests__/**', // test doubles of @heroui/react
    ],
    rules: {
      'no-restricted-imports': ['error', {
        paths: ['@heroui/react', '@heroui/modal'].map((name) => ({
          name,
          importNames: ['Modal'],
          message: 'Use ResponsiveModal from @/components/ui/ResponsiveModal: it opens full-screen on phones (ux-ui.md §5.4).',
        })),
      }],
    },
  },
  // #619: every API call goes through web/lib/api.ts (`request`, `client`):
  // the session cookie, the 15 s deadline and the reading of the API's error
  // codes live there once. Hand-written fetch calls had missed the deadline.
  // The service worker (generated by next-pwa, public/) is not linted.
  {
    files: ['**/*.{ts,tsx}'],
    ignores: [
      'lib/api.ts', // the one place that calls fetch
      '**/__tests__/**',
      '**/*.test.{ts,tsx}',
    ],
    rules: {
      'no-restricted-globals': ['error', { name: 'fetch', message: FETCH_MESSAGE }],
      'no-restricted-properties': ['error', ...['window', 'globalThis', 'self'].map((object) => ({
        object,
        property: 'fetch',
        message: FETCH_MESSAGE,
      }))],
    },
  },
  // #621: every React Query key comes from lib/queryKeys.ts, so "what does
  // this invalidation refresh?" is answered in one file, not by grepping the
  // hooks. Tests spell keys out on purpose (they check the exact key).
  {
    files: ['**/*.{ts,tsx}'],
    ignores: ['lib/queryKeys.ts', '**/*.test.{ts,tsx}', '**/__tests__/**'],
    rules: {
      'no-restricted-syntax': ['error',
        {
          selector: "Property[key.name='queryKey'] > ArrayExpression",
          message: 'Use a key from @/lib/queryKeys (qk.…) instead of a literal array (#621).',
        },
        {
          selector: "CallExpression[callee.property.name=/^(get|set)QueryData$|^getQueryState$/] > ArrayExpression:first-child",
          message: 'Use a key from @/lib/queryKeys (qk.…) instead of a literal array (#621).',
        },
        {
          // A key kept in a constant first (`const FOO_KEY = ['foo']`), query or mutation key alike.
          selector: 'VariableDeclarator[id.name=/(_KEY|Key)$/] > ArrayExpression',
          message: 'Declare the key in @/lib/queryKeys (qk.… or mutationKeys.…) instead of a literal array (#621).',
        },
      ],
    },
  },
];

